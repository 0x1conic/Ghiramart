  await admin.goto(base + '/admin/orders')
  await admin.waitForSelector('[data-booking-id]')
  const before = (await admin.$$('[data-booking-id]')).length
  await customer.goto(base + '/cart')
  await customer.waitForSelector('button[aria-label="Increase quantity"]')
  await customer.$eval('button[aria-label="Increase quantity"]', button => button.click())
  await customer.$eval('a[href="/checkout"]', link => link.click())
  await customer.waitForSelector('input[name="recipient"]')
  await customer.bringToFront()
  await customer.locator('input[name="recipient"]').fill('Booking Test Customer')
  await customer.locator('input[name="phone"]').fill('+977 9800000123')
  await customer.locator('input[name="address"]').fill('Demo Tole, Pokhara')
  await customer.locator('input[name="city"]').fill('Pokhara')
  await customer.evaluate(() => { const form = document.querySelector('main form'); form.requestSubmit(); form.requestSubmit() })
  await customer.waitForFunction(() => location.pathname.startsWith('/order-confirmation/'))
  const id = (await customer.evaluate(() => location.pathname)).split('/').at(-1)
  await admin.waitForSelector('[data-booking-id="' + id + '"]')
  assert.equal((await admin.$$('[data-booking-id]')).length, before + 1, 'Repeated submit produces one booking')
  const saved = await customer.evaluate(id => JSON.parse(localStorage.getItem('griha-mart:bookings:v1')).find(order => order.id === id), id)
  assert.equal(saved.status, 'new')
  assert.equal(saved.address.recipient, 'Booking Test Customer')
  assert.equal(saved.items[0].quantity, 2)
  assert.equal(saved.subtotal, saved.items.reduce((sum, item) => sum + item.price * item.quantity, 0))
  assert.equal(saved.total, saved.subtotal + saved.delivery + saved.memberCredit)
  assert.equal(saved.eta, undefined)
