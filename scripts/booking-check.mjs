import puppeteer from 'puppeteer-core'
import assert from 'node:assert/strict'

const base = process.env.SMOKE_BASE_URL || 'http://127.0.0.1:4173'
const browser = await puppeteer.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage', '--disable-gpu'] })
const customer = await browser.newPage()
const admin = await browser.newPage()
const errors = []
const delay = ms => new Promise(resolve => setTimeout(resolve, ms))
for (const page of [customer, admin]) {
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.setViewport({ width: 1440, height: 960 })
  await page.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'reduce' }])
}
async function click(page, label) {
  await page.waitForFunction(text => [...document.querySelectorAll('button')].some(button => button.textContent.trim() === text), {}, label)
  await page.$$eval('button', (buttons, text) => buttons.find(button => button.textContent.trim() === text).click(), label)
}
