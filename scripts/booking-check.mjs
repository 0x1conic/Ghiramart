  await admin.waitForFunction(() => document.body.textContent.includes('Booking Test Customer'))
  assert(await admin.evaluate(() => document.body.textContent.includes('Demo Tole, Pokhara')))
  await click(admin, 'Confirm booking')
  await customer.waitForFunction(() => document.body.textContent.includes('Confirmed by admin'))
  await customer.$eval('a[href="/market"]', link => link.click())
  await customer.waitForSelector('header a[href="/cart"]')
  await customer.$eval('header a[href="/cart"]', link => link.click())
  await customer.waitForFunction(() => document.body.textContent.includes('Your basket is ready for its first hero.'))
  await customer.goto(base + '/order-confirmation/' + id)
  await customer.waitForFunction(() => document.body.textContent.includes('Confirmed by admin'))
  await admin.reload()
  await admin.waitForFunction(() => document.body.textContent.includes('Confirmed by admin'))
