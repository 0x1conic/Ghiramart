  await customer.goto(base + '/checkout')
  await customer.waitForSelector('form')
  for (const [name, value] of Object.entries({ recipient: 'Demo Customer', phone: '+977 9800000123', address: 'Demo Tole', city: 'Pokhara' })) await customer.locator('input[name="' + name + '"]').fill(value)
  await customer.evaluate(() => { Storage.prototype.setItem = () => { throw new DOMException('Demo quota failure', 'QuotaExceededError') } })
