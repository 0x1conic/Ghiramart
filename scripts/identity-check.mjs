import puppeteer from 'puppeteer-core'
import assert from 'node:assert/strict'

const base = process.env.SMOKE_BASE_URL || 'http://127.0.0.1:4173'
const browser = await puppeteer.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage', '--disable-gpu'] })
const page = await browser.newPage()
const errors = []
page.on('pageerror', error => errors.push(error.message))
page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
const go = route => page.goto(base + route)
const fill = async values => { for (const [name, value] of Object.entries(values)) await page.locator('input[name="' + name + '"]').fill(value) }
const click = async label => page.evaluate(label => {
  const button = [...document.querySelectorAll('button')].find(node => node.textContent.trim().includes(label))
  if (!button) throw Error('Button missing: ' + label)
  button.click()
}, label)
const card = async name => { await go('/rewards'); await page.waitForSelector('[data-testid="member-card-name"]'); assert.equal(await page.$eval('[data-testid="member-card-name"]', node => node.textContent), name) }
const register = async (fullName, email) => {
  await go('/register')
  await fill({ fullName, email, phone: '+977 9800000123', password: 'test-only-password-937' })
  await page.$eval('.auth-submit', node => node.click())
  await page.waitForFunction(() => location.pathname === '/member')
}
try {
  await page.setViewport({ width: 1280, height: 960 })
  await page.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'reduce' }])
  const response = await go('/rewards')
  assert(response.headers()['content-security-policy'].includes("script-src 'self'"))
  assert(response.headers()['content-security-policy'].includes("frame-ancestors 'none'"))
  assert.equal(response.headers()['x-content-type-options'], 'nosniff')
  await card('Sign in to join')
  assert(!(await page.$eval('body', node => node.textContent)).includes('Bijaya'))
  await register('Asha Rai', 'asha@example.com')
  await card('Asha Rai')
  const first = await page.evaluate(() => JSON.parse(localStorage.getItem('griha-mart:demo-profiles:v1'))[0].user)
  assert.equal(first.rewardPoints, 0)
  await page.reload()
  await page.waitForSelector('[data-testid="member-card-name"]')
  assert.equal(await page.$eval('[data-testid="member-card-name"]', node => node.textContent), 'Asha Rai')
  await go('/account')
  const plainName = '<em>आशा & Rai</em>' // Inert formatting: must remain text, never become an HTML element.
  await fill({ fullName: plainName })
  await click('Save profile')
  await page.waitForFunction(() => document.body.textContent.includes('Profile saved.'))
  await card(plainName)
  assert.equal(await page.$('[data-testid="member-card-name"] em'), null)
  for (const width of [180, 320, 768]) {
    await page.setViewport({ width, height: 900 })
    for (const route of ['/rewards', '/member', '/account']) {
      await go(route)
      await page.waitForSelector('.identity-text')
      assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1), route + ' name overflow at ' + width)
    }
  }
  await page.setViewport({ width: 1280, height: 960 })
  await go('/member/addresses')
  await click('Add address')
  await fill({ label: 'Home', line1: 'Asha Demo Lane', city: 'Pokhara', phone: '+977 9800000123' })
  await click('Save address')
  await page.waitForFunction(() => document.body.textContent.includes('Asha Demo Lane'))
  await go('/checkout')
  assert.equal(await page.$eval('input[name="recipient"]', node => node.value), plainName)
  assert.equal(await page.$eval('input[name="address"]', node => node.value), 'Asha Demo Lane')
  await click('Place order')
  await page.waitForFunction(() => location.pathname.startsWith('/order-confirmation/'))
  const orderId = (await page.evaluate(() => location.pathname)).split('/').at(-1)
  const order = await page.evaluate(id => JSON.parse(localStorage.getItem('griha-mart:bookings:v1')).find(order => order.id === id), orderId)
  assert.equal(order.customerId, first.id)
  assert.equal(order.address.recipient, plainName)
  await go('/account'); await click('Sign out')
  await card('Sign in to join')
  await register('Nima Sherpa', 'nima@example.com')
  await card('Nima Sherpa')
  await go('/member/addresses')
  assert(!(await page.$eval('body', node => node.textContent)).includes('Asha Demo Lane'))
  await go('/order-confirmation/' + orderId)
  assert((await page.$eval('body', node => node.textContent)).includes('Booking not found.'))
  const profiles = await page.evaluate(() => JSON.parse(localStorage.getItem('griha-mart:demo-profiles:v1')))
  assert.notEqual(profiles[0].user.referralCode, profiles[1].user.referralCode)
  assert(!(await page.evaluate(() => JSON.stringify({ ...localStorage, ...sessionStorage }))).includes('test-only-password-937'))
  await go('/account'); await click('Sign out')
  await go('/login')
  await fill({ email: 'asha@example.com', password: 'test-only-password-937' })
  await page.$eval('.auth-submit', node => node.click())
  await page.waitForFunction(() => location.pathname === '/member')
  await card(plainName)
  await go('/order-confirmation/' + orderId)
  await page.waitForFunction(name => document.body.textContent.includes(name), {}, plainName)
  await go('/admin/orders/' + orderId)
  await page.waitForFunction(() => document.body.textContent.includes('Asha Demo Lane'))
  assert((await page.$eval('body', node => node.textContent)).includes(plainName))
  await go('/account'); await click('Sign out')
  await go('/login'); await fill({ email: 'unknown@example.com', password: 'test-only-password-937' })
  await page.$eval('.auth-submit', node => node.click())
  await page.waitForFunction(() => document.body.textContent.includes('No membership found'))
  assert.deepEqual(errors, [])
  console.log('PASS: dynamic identities, profile edits, inert markup as plain text, Unicode, 180–768px names, profile-specific addresses/orders, admin handoff, sign-out, persistence, no stored passwords, CSP headers; no browser errors. Demo filtering is not server authorization.')
} finally { await browser.close() }
