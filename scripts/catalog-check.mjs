import puppeteer from 'puppeteer-core'
import assert from 'node:assert/strict'
const browser = await puppeteer.launch({ executablePath: '/usr/bin/chromium', headless: true, args: ['--no-sandbox', '--disable-dev-shm-usage', '--disable-gpu'] })
const base = process.env.SMOKE_BASE_URL || 'http://127.0.0.1:4173'
const admin = await browser.newPage()
const shop = await browser.newPage()
const errors = []
for (const page of [admin, shop]) {
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(message.text()) })
  await page.emulateMediaFeatures([{ name: 'prefers-reduced-motion', value: 'reduce' }])
  await page.setViewport({ width: 1440, height: 1000 })
}
const delay = ms => new Promise(resolve => setTimeout(resolve, ms))
const click = (page, label) => page.$$eval('button', (buttons, label) => { const button = buttons.find(button => button.textContent.trim() === label); if (!button) throw new Error('No button ' + label); button.click() }, label)
const fill = async (name, value) => { await admin.bringToFront(); await admin.locator('[name="' + name + '"]').fill(value) }
try {
  await shop.goto(base + '/market')
  await shop.waitForSelector('.grocery-card')
  await admin.goto(base + '/admin/products/new')
  await admin.waitForSelector('input[name="name"]')
  assert.equal(await admin.$eval('input[name="name"]', input => input.value), '', 'New editor must not copy the rice fixture')
  await click(admin, 'Publish product')
  await admin.waitForSelector('[role="alert"]')
  await fill('name', 'Neighbourhood Masoor Dal Family Value Pack')
  await fill('sku', 'TEST-DAL-2026')
  await fill('unit', '2 × 1 kg family pack')
  await fill('price', '520')
  await fill('salePrice', '600')
  await fill('stock', '7')
  await click(admin, 'Publish product')
  await admin.waitForFunction(() => document.body.textContent.includes('below the regular price'))
  await fill('salePrice', '490')
  await admin.$eval('button[aria-label="Use Dal image"]', button => button.click())
  await click(admin, 'Save draft')
  await admin.waitForFunction(() => document.body.textContent.includes('Draft saved.'))
  assert.equal(await shop.$('a[aria-label="View Neighbourhood Masoor Dal Family Value Pack"]'), null)
  await click(admin, 'Publish product')
  await admin.waitForFunction(() => document.body.textContent.includes('Published. This product'))
  await shop.waitForSelector('a[aria-label="View Neighbourhood Masoor Dal Family Value Pack"]')
  const created = await admin.evaluate(() => JSON.parse(localStorage.getItem('griha-mart:products:v1')).find(product => product.sku === 'TEST-DAL-2026'))
  assert.equal(created.status, 'low-stock')
  await admin.reload()
  await admin.goto(base + '/admin/products/' + created.id + '/edit')
  await admin.waitForSelector('input[name="price"]')
  await fill('price', '550')
  await fill('salePrice', '500')
  await admin.$eval('input[name="featured"]', input => input.click())
  await click(admin, 'Publish product')
  await admin.waitForFunction(() => document.body.textContent.includes('Published. This product'))
  await shop.$eval('a[aria-label="View Neighbourhood Masoor Dal Family Value Pack"]', link => link.click())
  await shop.waitForFunction(() => document.body.textContent.includes('NPR 500'))
  await click(shop, 'Add 1 to pantry')
  await shop.$eval('header a[href="/cart"]', link => link.click())
  await shop.waitForSelector('a[href="/checkout"]')
  await shop.$eval('a[href="/checkout"]', link => link.click())
  await shop.waitForSelector('input[name="recipient"]')
  await shop.bringToFront()
  for (const [name, value] of Object.entries({ recipient: 'Demo Customer', phone: '+977 9800000123', address: 'Demo Tole', city: 'Pokhara' })) await shop.locator('input[name="' + name + '"]').fill(value)
  await click(shop, 'Place order')
  await shop.waitForFunction(() => location.pathname.startsWith('/order-confirmation/'))
  const booked = await shop.evaluate(() => JSON.parse(localStorage.getItem('griha-mart:bookings:v1'))[0])
  assert(booked.items.some(item => item.productId === created.id && item.price === 500), 'Admin-created product must reach booking service')
  await admin.screenshot({ path: '/tmp/griha-product-studio.png', fullPage: true })
  await click(admin, 'Archive product')
  await admin.waitForFunction(() => document.body.textContent.includes('Archived. Hidden'))
  await shop.goto(base + '/market')
  await shop.waitForSelector('.grocery-card')
  assert.equal(await shop.$('a[aria-label="View Neighbourhood Masoor Dal Family Value Pack"]'), null)
  await shop.goto(base + '/products/' + created.slug)
  await shop.waitForFunction(() => document.body.textContent.includes('This product is unavailable.'))
  await click(admin, 'Publish product')
  await admin.waitForFunction(() => document.body.textContent.includes('Published. This product'))
  const failures = []
  for (const width of [180, 200, 240, 320, 390, 768, 1440]) {
    await shop.setViewport({ width, height: 900 })
    for (const route of ['/', '/market', '/products/' + created.slug, '/cart', '/checkout', '/rewards', '/account', '/member', '/member/orders', '/login', '/register', '/admin/products', '/admin/products/' + created.id + '/edit']) {
      await shop.goto(base + route)
      await delay(350)
      const result = await shop.evaluate(() => ({ width: innerWidth, scroll: document.documentElement.scrollWidth, offenders: [...document.querySelectorAll('main *, section *')].filter(node => { const r = node.getBoundingClientRect(); return r.right > innerWidth + 1 && getComputedStyle(node).position !== 'absolute' }).slice(0, 5).map(node => ({ tag: node.tagName, class: node.className })) }))
      if (result.scroll > width + 1) failures.push({ route, ...result })
      if (route === '/market') {
        const artworkAlignment = await shop.$$eval('.grocery-card', cards => cards.map(card => {
          const media = card.querySelector('.grocery-card-media').getBoundingClientRect()
          const art = card.querySelector('.grocery-card-art').getBoundingClientRect()
          const image = card.querySelector('.grocery-card-art img').getBoundingClientRect()
          const details = card.querySelector('.grocery-card-details').getBoundingClientRect()
          return { artInsideMedia: art.top >= media.top && art.bottom <= media.bottom + 1, imageInsideArt: image.top >= art.top && image.bottom <= art.bottom + 1 && image.left >= art.left && image.right <= art.right + 1, artworkClipped: getComputedStyle(card.querySelector('.grocery-card-art')).overflow === 'hidden', sectionsSeparated: media.bottom <= details.top + 1, media: [Math.round(media.top), Math.round(media.bottom)], art: [Math.round(art.top), Math.round(art.bottom)], image: [Math.round(image.top), Math.round(image.bottom)], details: [Math.round(details.top), Math.round(details.bottom)] }
        }))
        assert(artworkAlignment.every(result => result.artInsideMedia && result.imageInsideArt && result.artworkClipped && result.sectionsSeparated), 'Full product artwork must stay inside its aligned media stage at ' + width + ': ' + JSON.stringify(artworkAlignment))
        const mediaHeights = artworkAlignment.map(result => result.media[1] - result.media[0])
        assert(Math.max(...mediaHeights) - Math.min(...mediaHeights) <= 1, 'Product media stages must have equal heights at ' + width)
        const collisions = await shop.$$eval('.grocery-card', cards => cards.filter(card => {
          const badge = card.querySelector('.grocery-card-badges').getBoundingClientRect()
          const heart = card.querySelector('.grocery-favourite').getBoundingClientRect()
          const button = card.querySelector('.grocery-card-add').getBoundingClientRect()
          const price = card.querySelector('.grocery-card-price').getBoundingClientRect()
          return badge.right > heart.left + 1 || (price.right > button.left && price.bottom > button.top + 1 && price.top < button.bottom && price.left < button.right)
        }).length)
        assert.equal(collisions, 0, 'Product card overlaps at ' + width)
        if ([180, 390].includes(width)) {
          await shop.$eval('.product-grid', node => node.scrollIntoView({ block: 'start', behavior: 'instant' }))
          await delay(1600)
          await shop.screenshot({ path: '/tmp/griha-catalog-' + width + '.png' })
        }
      }
    }
  }
  assert.deepEqual(failures, [], JSON.stringify(failures, null, 2))
  await shop.setViewport({ width: 180, height: 180 })
  await shop.goto(base + '/market')
  await shop.waitForSelector('.grocery-card-add')
  await shop.$eval('.grocery-card-add', node => node.scrollIntoView({ block: 'center', behavior: 'instant' }))
  await delay(250)
  assert.equal(await shop.$eval('.customer-header', node => getComputedStyle(node).position), 'relative', 'Short watch screen must not have a fixed header covering content')
  assert(await shop.$eval('.grocery-card-add', node => { const r = node.getBoundingClientRect(); return r.height >= 44 && r.top >= 0 && r.bottom < 130 }), 'Watch add button must remain reachable above bottom navigation')
  await shop.screenshot({ path: '/tmp/griha-catalog-watch.png' })
  await shop.focus('nav[aria-label="Mobile navigation"] a[href="/account"]')
  assert(await shop.$eval('nav[aria-label="Mobile navigation"]', node => node.scrollLeft > 0), 'All five watch navigation items remain keyboard reachable')
  assert(await shop.evaluate(() => document.documentElement.scrollWidth <= innerWidth + 1))
  assert.deepEqual(errors, [])
  console.log('PASS: draft/publish/edit/archive, persistence, live market sync, new product booking, card collision checks and 180–1440px routes; no console errors.')
} finally { await browser.close() }
